using System.Collections.Concurrent;
using System.Security.Cryptography;
using Laveyana.Security.Abstractions.Identifiers;
using Laveyana.Security.Nonce;

namespace Laveyana.Security.Software;

/// <summary>Tracks only live, freshly generated material for bounded forward encryption.</summary>
public sealed partial class SoftwareKeyProviderBackend
{
    // Provenance is intentionally local to the generating backend instance. It cannot
    // be restored from a store, imported, or transferred to another backend instance.
    // Bind the budget to exact material as well as identity: rollback may reuse a version
    // number for DIFFERENT freshly generated material. Never reset a matching budget.
    private readonly ConcurrentDictionary<(KeyReference Reference, string Fingerprint),
        AeadNoncePolicyEngine.NonceBudget> _freshNonceLifetimes = new();

    private static string NonceMaterialFingerprint(ReadOnlySpan<byte> material)
    {
        Span<byte> digest = stackalloc byte[32];
        SHA256.HashData(material, digest);
        string fingerprint = Convert.ToHexString(digest);
        CryptographicOperations.ZeroMemory(digest);
        return fingerprint;
    }

    private void RegisterFreshNonceLifetime(KeyReference reference, string fingerprint) =>
        // This is invoked only after a confirmed successful store commit. Reusing an
        // existing entry must NEVER reset the corresponding nonce budget.
        _freshNonceLifetimes.TryAdd((reference, fingerprint), new());

    private AeadNoncePolicyEngine.NonceBudget RequireFreshNonceLifetime(KeyReference reference,
        ReadOnlySpan<byte> material) =>
        _freshNonceLifetimes.TryGetValue((reference, NonceMaterialFingerprint(material)), out var budget)
            ? budget
            : throw new CryptographicException(
                "AES-GCM forward encryption requires material generated by this backend instance. " +
                "Stored/imported nonce history is unknown; rotate to a fresh version. Historical decryption remains available.");
}
